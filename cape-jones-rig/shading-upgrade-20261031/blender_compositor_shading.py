"""Blender 5.2.3 compositor N.L relight, light from left. Pattern follows
blender-composite-wrap-v4-20261031 (CompositorNodeTree, NodeGroupOutput,
render write_still). Inputs: apose plate PNG, normal-map PNG generated by
build_shading_upgrade.py (nx,ny,nz packed 0..1 in RGB, alpha = plate alpha).
Math: diffuse = clamp(Nx*Lx + Ny*Ly + Nz*Lz, 0, 1), L = (-0.80,-0.20,0.56)
normalised in the builder's convention (nx left-negative, ny up-positive,
nz toward viewer). Shade = 0.35 + 0.65*diffuse. Output = plate * shade,
alpha = plate alpha. This is a real Blender compositor run, not a PIL proxy,
when it completes; the script prints RENDERED with the output path.
"""
import bpy, os
R = '/home/hatch/workspace/cape-jones-rig'
OUTDIR = R + '/shading-upgrade-20261031'
PLATE = R + '/rig-apose-v7c-clean-transparent.png'
NORMAL = OUTDIR + '/normal-map-apose-20261031.png'
OUT = OUTDIR + '/V9-blender-compositor-lambert-LEFT-20261031.png'
BLEND = OUTDIR + '/blender-compositor-shading-20261031.blend'

def img(nodes, path, name, x, y, non_color=False):
    n = nodes.new('CompositorNodeImage'); n.name = name; n.location = (x, y)
    n.image = bpy.data.images.load(path)
    if non_color:
        # Normal maps MUST be Non-Color: sRGB decoding distorts nx,ny,ny
        # and was why the first V9 run was weaker than the PIL V2 run.
        n.image.colorspace_settings.name = 'Non-Color'
    return n

def math_node(nodes, links, op, a, b, name, x, y):
    m = nodes.new('ShaderNodeMath'); m.name = name; m.location = (x, y)
    m.operation = op
    if a is not None: links.new(a, m.inputs[0])
    if b is not None:
        if isinstance(b, float): m.inputs[1].default_value = b
        else: links.new(b, m.inputs[1])
    return m.outputs['Value']

bpy.ops.wm.read_factory_settings(use_empty=True)
scene = bpy.context.scene
scene.use_nodes = True; scene.render.use_compositing = True
scene.render.resolution_x = 1100; scene.render.resolution_y = 1500
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = 'PNG'
scene.render.image_settings.color_mode = 'RGBA'
scene.render.filepath = OUT
tree = bpy.data.node_groups.new('CapeJonesShading', 'CompositorNodeTree')
scene.compositing_node_group = tree
tree.interface.new_socket(name='Image', in_out='OUTPUT', socket_type='NodeSocketColor')
nodes = tree.nodes; links = tree.links
plate = img(nodes, PLATE, 'Plate', -900, 300)
nmap = img(nodes, NORMAL, 'NormalMap', -900, -300, non_color=True)
# Separate normal map RGB -> Nx,Ny,Nz in 0..1, convert to -1..1: v*2-1
sep = nodes.new('CompositorNodeSeparateColor'); sep.name = 'Normal_Sep'; sep.location = (-600, -300)
links.new(nmap.outputs['Image'], sep.inputs['Image'])
def to_signed(out, name, x):
    m = nodes.new('ShaderNodeMath'); m.name = name; m.location = (x, -300); m.operation = 'MULTIPLY'
    links.new(out, m.inputs[0]); m.inputs[1].default_value = 2.0
    s = nodes.new('ShaderNodeMath'); s.name = name + '_Sub'; s.location = (x + 200, -300); s.operation = 'SUBTRACT'
    links.new(m.outputs['Value'], s.inputs[0]); s.inputs[1].default_value = 1.0
    return s.outputs['Value']
nx = to_signed(sep.outputs['Red'], 'Nx', -300)
ny = to_signed(sep.outputs['Green'], 'Ny', -300)
nz = to_signed(sep.outputs['Blue'], 'Nz', -300)
# diffuse = clamp(nx*-0.80 + ny*-0.20 + nz*0.56, 0, 1)  (L already ~unit: sqrt(.64+.04+.3136)=0.997)
t1 = math_node(nodes, links, 'MULTIPLY', nx, -0.80, 'Nx_Lx', 300, -300)
t2 = math_node(nodes, links, 'MULTIPLY', ny, -0.20, 'Ny_Ly', 300, -100)
t3 = math_node(nodes, links, 'MULTIPLY', nz, 0.56, 'Nz_Lz', 300, 100)
a1 = math_node(nodes, links, 'ADD', t1, t2, 'Sum1', 600, -200)
a2 = math_node(nodes, links, 'ADD', a1, t3, 'Sum2', 800, -100)
# Clamp 0..1: MAX(0, v) then MIN(1, v) via Math nodes
mx = math_node(nodes, links, 'MAXIMUM', a2, 0.0, 'ClampLow', 1000, -100)
mn = math_node(nodes, links, 'MINIMUM', mx, 1.0, 'ClampHigh', 1200, -100)
# shade = 0.35 + 0.65*diffuse
sc = math_node(nodes, links, 'MULTIPLY', mn, 0.65, 'Diff_Scale', 1400, -100)
sh = math_node(nodes, links, 'ADD', sc, 0.35, 'Shade', 1600, -100)
# plate * shade: per-channel Math MULTIPLY + CombineColor (probed: both
# exist in Blender 5.2.3 compositor groups; MixRGB/Mix do NOT).
# Alpha: plate alpha via SeparateColor 'Alpha' output (known-good in v4).
psep = nodes.new('CompositorNodeSeparateColor'); psep.name = 'Plate_Sep'; psep.location = (-600, 300)
links.new(plate.outputs['Image'], psep.inputs['Image'])
outs = []
for i, ch in enumerate(['Red', 'Green', 'Blue']):
    m = nodes.new('ShaderNodeMath'); m.name = f'Ch_{ch}'; m.location = (1800, 300 - i * 200); m.operation = 'MULTIPLY'
    links.new(psep.outputs[ch], m.inputs[0]); links.new(sh, m.inputs[1]); outs.append(m.outputs['Value'])
comb = nodes.new('CompositorNodeCombineColor'); comb.name = 'Plate_Shaded'; comb.location = (2100, 100)
links.new(outs[0], comb.inputs['Red']); links.new(outs[1], comb.inputs['Green']); links.new(outs[2], comb.inputs['Blue'])
seta = nodes.new('CompositorNodeSetAlpha'); seta.name = 'SetAlpha'; seta.location = (2400, 100)
links.new(comb.outputs['Image'], seta.inputs['Image']); links.new(psep.outputs['Alpha'], seta.inputs['Alpha'])
out_node = nodes.new('NodeGroupOutput'); out_node.location = (2700, 100)
links.new(seta.outputs['Image'], out_node.inputs['Image'])
bpy.ops.wm.save_as_mainfile(filepath=BLEND)
bpy.ops.render.render(write_still=True)
print('RENDERED', OUT)
