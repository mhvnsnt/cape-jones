#!/usr/bin/env python3
"""
youtube_upload.py — YouTube upload automation for show episodes.

Uploads a finished video file to YouTube via the YouTube Data API v3 with
resumable upload, reading title/description/tags from a sidecar JSON file
(generated by metadata_gen.py) or from CLI flags.

Auth: OAuth 2.0 (desktop app flow) — credentials stored in client_secrets.json
and a cached token in token.json. One-time interactive auth, then headless.

Usage:
    pip install google-api-python-client google-auth-oauthlib
    python3 youtube_upload.py EP01_final.mp4 --meta EP01_meta.json
    python3 youtube_upload.py EP01_final.mp4 --title "..." --description "..." --tags a,b,c
    python3 youtube_upload.py EP01_final.mp4 --meta EP01_meta.json --privacy public --dry-run

client_secrets.json: from Google Cloud Console > YouTube Data API v3 > OAuth client ID (Desktop).
"""
import argparse
import json
import os
import sys
import http.client

import httplib2
from googleapiclient.discovery import build
from googleapiclient.errors import HttpError
from googleapiclient.http import MediaFileUpload
from google_auth_oauthlib.flow import InstalledAppFlow
from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials

SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]
API_SERVICE = "youtube"
API_VERSION = "v3"
MAX_RETRIES = 10
RETRIABLE_STATUS_CODES = [500, 502, 503, 504]
RETRIABLE_EXCEPTIONS = (httplib2.HttpLib2Error, IOError, http.client.NotConnected,
                        http.client.IncompleteRead, http.client.ImproperConnectionState,
                        http.client.CannotSendRequest, http.client.CannotSendHeader,
                        http.client.ResponseNotReady, http.client.BadStatusLine)


def get_authenticated_service(secrets="client_secrets.json", token="token.json"):
    creds = None
    if os.path.exists(token):
        creds = Credentials.from_authorized_user_file(token, SCOPES)
    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            creds.refresh(Request())
        else:
            if not os.path.exists(secrets):
                sys.exit(f"ERROR: {secrets} missing — create an OAuth desktop client at "
                         "https://console.cloud.google.com/apis/credentials and download it.")
            flow = InstalledAppFlow.from_client_secrets_file(secrets, SCOPES)
            creds = flow.run_local_server(port=0)
        with open(token, "w") as f:
            f.write(creds.to_json())
    return build(API_SERVICE, API_VERSION, credentials=creds)


def resumable_upload(request):
    response = None
    retries = 0
    while response is None:
        try:
            status, response = request.next_chunk()
            if response is not None and "id" in response:
                return response
        except HttpError as e:
            if e.resp.status in RETRIABLE_STATUS_CODES:
                pass
            else:
                raise
        except RETRIABLE_EXCEPTIONS:
            pass
        retries += 1
        if retries > MAX_RETRIES:
            sys.exit("ERROR: upload failed after max retries.")
        print(f"  retry {retries}/{MAX_RETRIES} ...")


def main():
    ap = argparse.ArgumentParser(description="Upload a video to YouTube with metadata.")
    ap.add_argument("video", help="Path to the video file")
    ap.add_argument("--meta", help="JSON sidecar from metadata_gen.py")
    ap.add_argument("--title")
    ap.add_argument("--description")
    ap.add_argument("--tags", help="Comma-separated tags")
    ap.add_argument("--category", default="24", help="YouTube category id (24=Entertainment)")
    ap.add_argument("--privacy", default="private", choices=["public", "unlisted", "private"])
    ap.add_argument("--made-for-kids", action="store_true")
    ap.add_argument("--language", default="en")
    ap.add_argument("--secrets", default="client_secrets.json")
    ap.add_argument("--token", default="token.json")
    ap.add_argument("--dry-run", action="store_true", help="Print request body, do not upload")
    args = ap.parse_args()

    meta = {}
    if args.meta:
        with open(args.meta) as f:
            meta = json.load(f)

    title = args.title or meta.get("title") or os.path.splitext(os.path.basename(args.video))[0]
    description = args.description or meta.get("description", "")
    tags = (args.tags.split(",") if args.tags else meta.get("tags", []))

    body = {
        "snippet": {
            "title": title[:100],
            "description": description,
            "tags": [t.strip() for t in tags if t.strip()][:500],
            "categoryId": args.category,
            "defaultLanguage": args.language,
        },
        "status": {
            "privacyStatus": args.privacy,
            "selfDeclaredMadeForKids": args.made_for_kids,
        },
    }

    if args.dry_run:
        print(json.dumps(body, indent=2)[:2000])
        print(f"\n[DRY RUN] would upload: {args.video} ({os.path.getsize(args.video)} bytes)")
        return

    youtube = get_authenticated_service(args.secrets, args.token)
    print(f"Uploading {args.video} as {args.privacy} ...")
    media = MediaFileUpload(args.video, chunksize=8 * 1024 * 1024, resumable=True)
    resp = resumable_upload(youtube.videos().insert(
        part="snippet,status", body=body, media_body=media))
    print(f"DONE — https://www.youtube.com/watch?v={resp['id']}")


if __name__ == "__main__":
    main()
